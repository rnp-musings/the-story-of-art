   "The stage is simple. Two string beds are stood upright with bamboo poles tied across, a dark curtain hangs at the back, and a coloured three-arched curtain called tibara hangs in front to hide the puppeteers. The puppeteers control the hands, neck and shoulders through strings wound around their fingers. A dholak gives the rhythm and women sing songs that go with the dialogue.",
